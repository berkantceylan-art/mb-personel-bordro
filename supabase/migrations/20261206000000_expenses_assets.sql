-- Aylık amortisman (normal / doğrusal): (maliyet − hurda) / ömür; tek finans kaydı
create or replace function asset_depreciation_run(p_period date) returns jsonb
language plpgsql security definer set search_path = public as $$
declare
  v_month date := date_trunc('month', coalesce(p_period, current_date))::date; v_end date; a record; v_acc bigint; v_monthly bigint; v_amt bigint; v_total bigint := 0; n int := 0; v_txn uuid;
begin
  if not can_module('assets', 2) then raise exception 'not_allowed'; end if;
  v_end := (v_month + interval '1 month - 1 day')::date;
  for a in select * from assets
           where company_id = lab_company() and depreciation_method = 'straight' and coalesce(value, 0) > 0 and useful_life_months > 0
             and coalesce(depreciation_start, purchase_date) is not null and coalesce(depreciation_start, purchase_date) <= v_end
             and (disposed_on is null or disposed_on > v_end)
             and not exists (select 1 from asset_depreciation d where d.asset_id = assets.id and d.period = v_month) loop
    select coalesce(sum(amount), 0) into v_acc from asset_depreciation where asset_id = a.id;
    v_monthly := round((a.value - a.salvage_value)::numeric / a.useful_life_months);
    v_amt := least(v_monthly, a.value - a.salvage_value - v_acc);
    if v_amt > 0 then
      insert into asset_depreciation (asset_id, period, amount) values (a.id, v_month, v_amt);
      v_total := v_total + v_amt; n := n + 1;
    end if;
  end loop;
  if v_total > 0 then
    v_txn := fin_post_sys(jsonb_build_object('kind', 'depreciation', 'txn_date', v_end, 'description', 'Amortisman · ' || to_char(v_month, 'MM.YYYY') || ' (' || n || ' demirbaş)', 'amount', v_total, 'currency', 'TRY', 'ref_type', 'depreciation'),
      jsonb_build_array(jsonb_build_object('category_id', fin_category('exp_depreciation'), 'amount', v_total, 'currency', 'TRY', 'rate', 1),
                        jsonb_build_object('category_id', fin_category('fixed_assets'), 'amount', -v_total, 'currency', 'TRY', 'rate', 1, 'description', 'Birikmiş amortisman')));
    update asset_depreciation set txn_id = v_txn where period = v_month and txn_id is null;
  end if;
  return jsonb_build_object('count', n, 'total', v_total, 'txn', v_txn);
end $$;
revoke execute on function asset_depreciation_run(date) from public, anon;
grant execute on function asset_depreciation_run(date) to authenticated;

create or replace function asset_depreciation_undo(p_period date) returns int
language plpgsql security definer set search_path = public as $$
declare v_month date := date_trunc('month', p_period)::date; t uuid; n int;
begin
  if not can_module('assets', 3) then raise exception 'not_allowed'; end if;
  for t in select distinct d.txn_id from asset_depreciation d join assets a on a.id = d.asset_id where d.period = v_month and a.company_id = lab_company() and d.txn_id is not null loop
    perform fin_void_sys(t, 'Amortisman geri alındı');
  end loop;
  delete from asset_depreciation d using assets a where a.id = d.asset_id and d.period = v_month and a.company_id = lab_company();
  get diagnostics n = row_count;
  return n;
end $$;
revoke execute on function asset_depreciation_undo(date) from public, anon;
grant execute on function asset_depreciation_undo(date) to authenticated;

-- Bakım / onarım kaydı (maliyet varsa gider olarak işlenir)
--  p: {asset_id, done_on, kind, description, cost, vat_rate, account_id | party_id, next_due}
create or replace function asset_maintenance_add(p jsonb) returns uuid
language plpgsql security definer set search_path = public as $$
declare
  a assets; v_id uuid; v_cost bigint := coalesce(nullif(p->>'cost', '')::bigint, 0); v_vr numeric := coalesce(nullif(p->>'vat_rate', '')::numeric, 20);
  v_vat bigint; v_date date := coalesce(nullif(p->>'done_on', '')::date, current_date); acc fin_accounts; pt fin_parties; v_txn uuid; v_next date;
begin
  if not can_module('assets', 2) then raise exception 'not_allowed'; end if;
  select * into a from assets where id = (p->>'asset_id')::uuid;
  if a.id is null then raise exception 'not_found'; end if;
  v_next := coalesce(nullif(p->>'next_due', '')::date, case when a.maintenance_interval_months is not null then (v_date + make_interval(months => a.maintenance_interval_months))::date end);
  if v_cost > 0 then
    v_vat := case when v_vr > 0 then round(v_cost * v_vr / (100 + v_vr)) else 0 end;
    select * into acc from fin_accounts where id = nullif(p->>'account_id', '')::uuid and kind in ('cash', 'bank', 'credit_card');
    select * into pt from fin_parties where id = nullif(p->>'party_id', '')::uuid;
    if acc.id is null and pt.id is null then raise exception 'account_required'; end if;
    v_txn := fin_post_sys(jsonb_build_object('kind', case when acc.kind = 'credit_card' then 'card_spend' else 'expense' end, 'txn_date', v_date,
                                             'description', 'Demirbaş bakımı · ' || a.name || coalesce(' · ' || nullif(p->>'description', ''), ''), 'amount', v_cost, 'currency', 'TRY',
                                             'account_id', acc.id, 'party_id', pt.id, 'ref_type', 'asset', 'ref_id', a.id),
      jsonb_build_array(
        case when acc.id is not null then jsonb_build_object('account_id', acc.id, 'amount', -fin_conv(v_cost, 'TRY', acc.currency, v_date), 'currency', acc.currency, 'rate', fin_rate(acc.currency, v_date))
             else jsonb_build_object('party_id', pt.id, 'amount', -fin_conv(v_cost, 'TRY', pt.currency, v_date), 'currency', pt.currency, 'rate', fin_rate(pt.currency, v_date)) end,
        jsonb_build_object('category_id', fin_category('exp_maintenance'), 'amount', v_cost - v_vat, 'currency', 'TRY', 'rate', 1),
        jsonb_build_object('category_id', fin_category('vat_in'), 'amount', v_vat, 'currency', 'TRY', 'rate', 1)));
  end if;
  insert into asset_maintenance (asset_id, done_on, kind, description, cost, party_id, next_due, fin_txn_id)
  values (a.id, v_date, coalesce(nullif(p->>'kind', ''), 'maintenance'), nullif(left(p->>'description', 500), ''), v_cost, pt.id, v_next, v_txn)
  returning id into v_id;
  update assets set next_maintenance = v_next, status = case when status = 'MAINTENANCE' then 'AVAILABLE' else status end, updated_at = now() where id = a.id;
  return v_id;
end $$;
revoke execute on function asset_maintenance_add(jsonb) from public, anon;
grant execute on function asset_maintenance_add(jsonb) to authenticated;

-- Satış / hurda: durum hurda; satış bedeli varsa kasaya / bankaya gelir
create or replace function asset_dispose(p_asset uuid, p_date date, p_amount bigint, p_account uuid, p_note text) returns void
language plpgsql security definer set search_path = public as $$
declare a assets; acc fin_accounts; v_txn uuid;
begin
  if not can_module('assets', 3) then raise exception 'not_allowed'; end if;
  select * into a from assets where id = p_asset for update;
  if a.id is null then raise exception 'not_found'; end if;
  if exists (select 1 from asset_assignments where asset_id = a.id and returned_on is null) then raise exception 'asset_assigned'; end if;
  if coalesce(p_amount, 0) > 0 then
    select * into acc from fin_accounts where id = p_account and kind in ('cash', 'bank');
    if acc.id is null then raise exception 'account_required'; end if;
    v_txn := fin_post_sys(jsonb_build_object('kind', 'income', 'txn_date', coalesce(p_date, current_date), 'description', 'Demirbaş satışı · ' || a.name, 'amount', p_amount, 'currency', 'TRY', 'account_id', acc.id, 'ref_type', 'asset', 'ref_id', a.id),
      jsonb_build_array(jsonb_build_object('account_id', acc.id, 'amount', fin_conv(p_amount, 'TRY', acc.currency, coalesce(p_date, current_date)), 'currency', acc.currency, 'rate', fin_rate(acc.currency, coalesce(p_date, current_date))),
                        jsonb_build_object('category_id', fin_category('income_other'), 'amount', -p_amount, 'currency', 'TRY', 'rate', 1)));
  end if;
  update assets set status = 'RETIRED', disposed_on = coalesce(p_date, current_date), disposal_amount = nullif(p_amount, 0), disposal_note = nullif(left(coalesce(p_note, ''), 300), ''), updated_at = now() where id = a.id;
end $$;
revoke execute on function asset_dispose(uuid, date, bigint, uuid, text) from public, anon;
grant execute on function asset_dispose(uuid, date, bigint, uuid, text) to authenticated;

-- Önceden alınmış demirbaşın değerini finansa açılış olarak işle (amortisman karşılığı doğru görünsün)
create or replace function asset_open_post(p_asset uuid) returns uuid
language plpgsql security definer set search_path = public as $$
declare a assets; v_txn uuid;
begin
  if not can_module('assets', 2) then raise exception 'not_allowed'; end if;
  select * into a from assets where id = p_asset for update;
  if a.id is null or coalesce(a.value, 0) <= 0 or a.opening_txn_id is not null or a.invoice_id is not null then return null; end if;
  v_txn := fin_post_sys(jsonb_build_object('kind', 'opening', 'txn_date', coalesce(a.purchase_date, current_date), 'description', 'Demirbaş açılış · ' || a.name, 'amount', a.value, 'currency', 'TRY', 'ref_type', 'asset', 'ref_id', a.id),
    jsonb_build_array(jsonb_build_object('category_id', fin_category('fixed_assets'), 'amount', a.value, 'currency', 'TRY', 'rate', 1),
                      jsonb_build_object('category_id', fin_category('opening'), 'amount', -a.value, 'currency', 'TRY', 'rate', 1)));
  update assets set opening_txn_id = v_txn where id = a.id;
  return v_txn;
end $$;
revoke execute on function asset_open_post(uuid) from public, anon;
grant execute on function asset_open_post(uuid) to authenticated;

-- Kaynağından geri alınması gereken finans kayıtları
create or replace function fin_void(p_txn uuid, p_reason text) returns void
language plpgsql security definer set search_path = public as $$
declare t fin_txns;
begin
  select * into t from fin_txns where id = p_txn for update;
  if t.id is null then raise exception 'not_found'; end if;
  if not (can_module('finance', 3) or (t.kind = 'expense' and can_module('expenses', 3))) then raise exception 'not_allowed'; end if;
  if t.voided_at is not null then return; end if;
  if t.ref_type = 'invoice' then raise exception 'use_invoice_cancel'; end if;
  if t.ref_type in ('cheque', 'loan', 'expense_claim', 'depreciation') then raise exception 'use_source_undo'; end if;
  update fin_txns set voided_at = now(), voided_by = auth.uid(), void_reason = left(coalesce(p_reason, ''), 300) where id = p_txn;
  if t.lab_payment_id is not null then delete from lab_payments where id = t.lab_payment_id; end if;
end $$;
revoke execute on function fin_void(uuid, text) from public, anon;
grant execute on function fin_void(uuid, text) to authenticated;

