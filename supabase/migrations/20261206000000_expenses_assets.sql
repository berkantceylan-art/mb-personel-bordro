-- Onay / red → finansa işleme
--  p: {method: account|advance|payable, account_id, party_id, category_id, vat_rate, date, reason}
create or replace function exp_claim_decide(p_id uuid, p_decision text, p jsonb default '{}'::jsonb) returns uuid
language plpgsql security definer set search_path = public as $$
declare
  c exp_claims; a fin_accounts; pt fin_parties; v_aid uuid; v_cat uuid; v_vr numeric; v_vat bigint; v_txn uuid; v_date date; v_kind text; v_first jsonb; v_who text;
begin
  if not can_module('expenses', 2) then raise exception 'not_allowed'; end if;
  select * into c from exp_claims where id = p_id for update;
  if c.id is null then raise exception 'not_found'; end if;
  if c.status <> 'submitted' then raise exception 'bad_status'; end if;
  if p_decision = 'reject' then
    update exp_claims set status = 'rejected', decided_by = auth.uid(), decided_at = now(), reject_reason = nullif(left(p->>'reason', 300), '') where id = c.id;
    return null;
  end if;
  v_cat := coalesce(nullif(p->>'category_id', '')::uuid, c.category_id, fin_category('exp_other'));
  v_vr := coalesce(nullif(p->>'vat_rate', '')::numeric, c.vat_rate);
  v_vat := case when v_vr > 0 then round(c.amount * v_vr / (100 + v_vr)) else 0 end;
  v_date := coalesce(nullif(p->>'date', '')::date, c.expense_date);
  select coalesce(e.first_name || ' ' || e.last_name, '') into v_who from employees e where e.id = c.employee_id;
  if p->>'method' = 'advance' then
    if c.employee_id is null then raise exception 'employee_required'; end if;
    v_aid := fin_advance_account(c.employee_id, c.currency);
    select * into a from fin_accounts where id = v_aid;
    v_kind := 'advance_close';
    v_first := jsonb_build_object('account_id', a.id, 'amount', -c.amount, 'currency', c.currency, 'rate', fin_rate(c.currency, v_date));
  elsif p->>'method' = 'payable' then
    select * into pt from fin_parties where id = coalesce(nullif(p->>'party_id', '')::uuid, c.party_id);
    if pt.id is null then raise exception 'party_required'; end if;
    v_kind := 'expense';
    v_first := jsonb_build_object('party_id', pt.id, 'amount', -fin_conv(c.amount, c.currency, pt.currency, v_date), 'currency', pt.currency, 'rate', fin_rate(pt.currency, v_date));
  else
    select * into a from fin_accounts where id = coalesce(nullif(p->>'account_id', '')::uuid, c.account_id) and kind in ('cash', 'bank', 'credit_card', 'advance', 'partner');
    if a.id is null then raise exception 'account_required'; end if;
    v_kind := case when a.kind = 'credit_card' then 'card_spend' when a.kind = 'advance' then 'advance_close' when a.kind = 'partner' then 'partner_in' else 'expense' end;
    v_first := jsonb_build_object('account_id', a.id, 'amount', -fin_conv(c.amount, c.currency, a.currency, v_date), 'currency', a.currency, 'rate', fin_rate(a.currency, v_date));
  end if;
  v_txn := fin_post_sys(
    jsonb_build_object('kind', v_kind, 'txn_date', v_date, 'description', 'Masraf #' || c.no || coalesce(' · ' || nullif(c.vendor, ''), '') || coalesce(' · ' || nullif(c.description, ''), '') || case when v_who <> '' then ' (' || v_who || ')' else '' end,
                       'doc_no', c.doc_no, 'amount', c.amount, 'currency', c.currency, 'account_id', a.id, 'party_id', pt.id, 'category_id', v_cat, 'ref_type', 'expense_claim', 'ref_id', c.id, 'attachment_path', c.receipt_path),
    jsonb_build_array(v_first,
      jsonb_build_object('category_id', v_cat, 'amount', c.amount - v_vat, 'currency', c.currency, 'rate', fin_rate(c.currency, v_date)),
      jsonb_build_object('category_id', fin_category('vat_in'), 'amount', v_vat, 'currency', c.currency, 'rate', fin_rate(c.currency, v_date))));
  update exp_claims set status = 'posted', decided_by = auth.uid(), decided_at = now(), fin_txn_id = v_txn, category_id = v_cat, vat_rate = v_vr,
    pay_method = coalesce(nullif(p->>'method', ''), 'account'), account_id = a.id, party_id = pt.id
  where id = c.id;
  return v_txn;
end $$;
revoke execute on function exp_claim_decide(uuid, text, jsonb) from public, anon;
grant execute on function exp_claim_decide(uuid, text, jsonb) to authenticated;

