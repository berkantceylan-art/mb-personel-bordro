-- Tekrarlayan masrafları vakti gelince onay kuyruğuna koy (günlük zamanlanmış iş ve masraf sayfası çağırır)
create or replace function exp_recurring_run(p_date date default current_date) returns int
language plpgsql security definer set search_path = public as $$
declare r exp_recurring; v_month date := date_trunc('month', p_date)::date; v_day date; n int := 0;
begin
  if auth.uid() is not null and not can_module('expenses', 2) then return 0; end if;
  for r in select * from exp_recurring where is_active and start_date <= p_date and (end_date is null or end_date >= v_month)
                                         and (last_period is null or last_period < v_month) and day_of_month <= extract(day from p_date) loop
    v_day := make_date(extract(year from v_month)::int, extract(month from v_month)::int, r.day_of_month);
    insert into exp_claims (company_id, expense_date, amount, currency, vat_rate, category_id, description, pay_method, account_id, party_id, recurring_id, submitted_by)
    values (r.company_id, v_day, r.amount, r.currency, r.vat_rate, r.category_id, r.name, case when r.party_id is not null and r.account_id is null then 'payable' else 'account' end,
            r.account_id, r.party_id, r.id, null)
    on conflict do nothing;
    update exp_recurring set last_period = v_month where id = r.id;
    n := n + 1;
  end loop;
  return n;
end $$;
revoke execute on function exp_recurring_run(date) from public, anon;
grant execute on function exp_recurring_run(date) to authenticated;
do $$ begin if exists (select 1 from pg_roles where rolname = 'service_role') then grant execute on function exp_recurring_run(date) to service_role; end if; end $$;

