-- İrsaliye / aylık fatura sihirbazı:
--  1) Faturaya girecek irsaliyeleri seçerek fatura kesme
--  2) Belge izleri: yazdırıldı / e-posta / WhatsApp / Excel (kim, ne zaman, kime)

create table if not exists lab_doc_events (
  id bigint generated by default as identity primary key,
  company_id uuid not null default lab_company() references companies (id) on delete cascade,
  doc_kind text not null check (doc_kind in ('waybill', 'statement')),
  doc_id uuid not null,
  action text not null check (action in ('print', 'email', 'whatsapp', 'excel')),
  target text check (target is null or length(target) <= 200),
  by_user uuid,
  at timestamptz not null default now()
);
create index if not exists lab_doc_events_idx on lab_doc_events (doc_kind, doc_id);
alter table lab_doc_events enable row level security;
drop policy if exists lab_doc_events_read on lab_doc_events;
create policy lab_doc_events_read on lab_doc_events for select to authenticated
  using (company_id = (select lab_company()) and ((select can_logistics()) or (select can_module('sales'))));
revoke all on lab_doc_events from anon;
grant select on lab_doc_events to authenticated;

-- Seçilen irsaliyelerden tek fatura (dönem = seçilenlerin ilk–son tarihi)
create or replace function lab_statement_create_sel(p_customer uuid, p_waybills uuid[], p_issue date default null, p_note text default null) returns uuid
language plpgsql security definer set search_path = public as $$
declare c lab_customers; v_id uuid; v_issue date; v_from date; v_to date; v_cur text; v_n int;
begin
  perform lab_waybill_guard();
  select * into c from lab_customers where id = p_customer and company_id = lab_company();
  if c.id is null then raise exception 'not_found'; end if;
  if coalesce(array_length(p_waybills, 1), 0) = 0 then raise exception 'nothing_to_invoice'; end if;
  select count(distinct w.currency), min(w.ship_date), max(w.ship_date) into v_n, v_from, v_to from lab_waybills w where w.id = any(p_waybills);
  if exists (select 1 from lab_waybills w where w.id = any(p_waybills) and (w.customer_id <> p_customer or w.status = 'cancelled' or w.statement_id is not null)) then
    raise exception 'waybill_not_available';
  end if;
  if v_n > 1 then raise exception 'mixed_currency'; end if;
  select currency into v_cur from lab_waybills where id = any(p_waybills) limit 1;
  v_issue := coalesce(p_issue, v_to);
  insert into lab_statements (year, no, customer_id, period_from, period_to, issue_date, due_date, currency, lang, note)
  values (extract(year from v_issue)::int, lab_next_no('statement', extract(year from v_issue)::int), p_customer, v_from, v_to, v_issue,
          v_issue + coalesce(nullif(c.payment_term_days, 0), 30), v_cur, c.doc_lang, nullif(trim(p_note), ''))
  returning id into v_id;
  update lab_waybills set statement_id = v_id, status = 'issued', issued_at = coalesce(issued_at, now()) where id = any(p_waybills);
  update lab_statements s set job_count = x.n, total = x.t, unit_count = x.u
  from (select sum(job_count) n, sum(total) t, sum(unit_count) u from lab_waybills where statement_id = v_id) x where s.id = v_id;
  return v_id;
end $$;
revoke execute on function lab_statement_create_sel(uuid, uuid[], date, text) from public, anon;
grant execute on function lab_statement_create_sel(uuid, uuid[], date, text) to authenticated;
