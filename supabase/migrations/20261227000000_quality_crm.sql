begin
  if not qms_read() then raise exception 'not_allowed'; end if;
  update srv_responses set sent_at = coalesce(sent_at, now()) where id = any (p_ids);
end $$;
revoke execute on function srv_mark_sent(uuid[]) from public, anon;
