create table if not exists crm_leads (
  id uuid primary key default gen_random_uuid(),
  company_id uuid references companies (id) on delete cascade default lab_company(),
  name text not null check (length(name) between 1 and 160),
  contact_name text check (contact_name is null or length(contact_name) <= 120),
  phone text check (phone is null or length(phone) <= 40),
  email text check (email is null or length(email) <= 200),
  city text check (city is null or length(city) <= 80),
  country text not null default 'TR' check (length(country) <= 60),
  source text not null default 'other' check (source in ('website', 'referral', 'visit', 'fair', 'social', 'phone', 'other')),
  stage text not null default 'new' check (stage in ('new', 'contacted', 'sample', 'offer', 'won', 'lost')),
  est_monthly bigint check (est_monthly is null or est_monthly >= 0),   -- tahmini aylık ciro (TL kuruş)
