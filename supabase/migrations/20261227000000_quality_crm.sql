create or replace function srv_public(p_token text) returns jsonb
language sql stable security definer set search_path = public as $$
  select jsonb_build_object('customer', c.name, 'job_no', j.no, 'patient', j.patient, 'delivered', (j.delivered_at at time zone 'Europe/Istanbul')::date,
                            'score', s.score, 'answered', s.answered_at is not null, 'lang', coalesce(c.doc_lang, 'tr'), 'company', (select name from companies where id = s.company_id))
  from srv_responses s left join lab_customers c on c.id = s.customer_id left join jobs j on j.id = s.job_id
  where s.token = p_token and length(p_token) >= 24;
$$;
revoke execute on function srv_public(text) from public;
grant execute on function srv_public(text) to anon, authenticated;

-- Yanıt: 1-2 puan → şikâyet kaydı açılır
create or replace function srv_answer(p_token text, p_score int, p_comment text default null) returns boolean
language plpgsql security definer set search_path = public as $$
declare s srv_responses; v_c uuid;
begin
  if p_score is null or p_score not between 1 and 5 then raise exception 'bad_score'; end if;
  select * into s from srv_responses where token = p_token and length(p_token) >= 24 for update;
  if s.id is null or s.answered_at is not null then return false; end if;
  update srv_responses set score = p_score, comment = nullif(left(trim(coalesce(p_comment, '')), 1000), ''), answered_at = now(), sent_at = coalesce(sent_at, now()) where id = s.id;
  if p_score <= 2 then
    insert into qms_complaints (company_id, customer_id, job_id, source, category, severity, description)
    values (s.company_id, s.customer_id, s.job_id, 'survey', 'other', case when p_score = 1 then 'high' else 'medium' end,
            left('Anket puanı ' || p_score || '/5' || coalesce(': ' || nullif(trim(p_comment), ''), ''), 2000))
    returning id into v_c;
    update srv_responses set complaint_id = v_c where id = s.id;
  end if;
  return true;
end $$;
revoke execute on function srv_answer(text, int, text) from public;
grant execute on function srv_answer(text, int, text) to anon, authenticated;

-- Kalite özeti
create or replace function qms_summary(p_days int default 90) returns jsonb
language sql stable security definer set search_path = public as $$
  select case when not qms_read() then null else jsonb_build_object(
    'open_complaints', (select count(*) from qms_complaints where status <> 'closed'),
    'complaints', (select count(*) from qms_complaints where received_at >= now() - make_interval(days => p_days)),
    'units', (select coalesce(sum(job_units(j.id)), 0) from jobs j where j.status = 'delivered' and j.delivered_at >= now() - make_interval(days => p_days)),
    'by_category', (select coalesce(jsonb_object_agg(category, n), '{}') from (select category, count(*) n from qms_complaints where received_at >= now() - make_interval(days => p_days) group by category) x),
    'open_ncrs', (select count(*) from qms_ncrs where status <> 'closed'),
    'overdue_actions', (select count(*) from qms_actions a join qms_ncrs n on n.id = a.ncr_id where a.done_at is null and a.due_date < current_date and n.status <> 'closed'),
    'avg_close_days', (select round(avg(extract(epoch from closed_at - received_at) / 86400)::numeric, 1) from qms_complaints where closed_at >= now() - make_interval(days => p_days)),
    'survey_avg', (select round(avg(score)::numeric, 2) from srv_responses where answered_at >= now() - make_interval(days => p_days)),
    'survey_n', (select count(*) from srv_responses where answered_at >= now() - make_interval(days => p_days))
  ) end;
$$;

