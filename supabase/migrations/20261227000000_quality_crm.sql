-- Kazanıldı: hekim kartı açılır (varsa bağlanır)
create or replace function crm_lead_convert(p_lead uuid, p_kind text default 'doctor_tr', p_currency text default 'TRY') returns uuid
language plpgsql security definer set search_path = public as $$
declare l crm_leads; v_c uuid;
begin
  if not crm_write() then raise exception 'not_allowed'; end if;
  select * into l from crm_leads where id = p_lead for update;
  if l.id is null then raise exception 'not_found'; end if;
  if l.customer_id is not null then return l.customer_id; end if;
  select id into v_c from lab_customers where lower(name) = lower(l.name) limit 1;
  if v_c is null then
    insert into lab_customers (company_id, name, kind, currency, phone, email, country, city, note)
    values (lab_company(), l.name, case when p_kind in ('doctor_tr', 'doctor_foreign', 'clinic', 'hospital', 'agency') then p_kind else 'doctor_tr' end,
            case when p_currency in ('TRY', 'EUR', 'USD') then p_currency else 'TRY' end, l.phone, l.email, coalesce(l.country, 'TR'), l.city,
            nullif(concat_ws(' · ', 'CRM: ' || l.source, l.contact_name, l.note), ''))
    returning id into v_c;
  end if;
  update crm_leads set customer_id = v_c, stage = 'won' where id = l.id;
  update crm_activities set customer_id = v_c where lead_id = l.id and customer_id is null;
  return v_c;
end $$;
revoke execute on function crm_lead_convert(uuid, text, text) from public, anon;
grant execute on function crm_lead_convert(uuid, text, text) to authenticated;

