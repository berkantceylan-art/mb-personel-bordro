do $rls$
declare t text;
begin
  foreach t in array array['qms_complaints', 'qms_ncrs', 'qms_actions', 'qms_audits'] loop
    execute format('alter table %I enable row level security', t);
    execute format('drop policy if exists %I on %I', t || '_read', t);
    execute format('create policy %I on %I for select to authenticated using (qms_read())', t || '_read', t);
    execute format('drop policy if exists %I on %I', t || '_write', t);
    execute format('create policy %I on %I for all to authenticated using (qms_write()) with check (qms_write())', t || '_write', t);
    execute format('grant select, insert, update, delete on %I to authenticated', t);
  end loop;
end $rls$;
