create index if not exists crm_leads_stage_idx on crm_leads (stage, next_date);

create table if not exists crm_activities (
  id uuid primary key default gen_random_uuid(),
  company_id uuid references companies (id) on delete cascade default lab_company(),
  lead_id uuid references crm_leads (id) on delete cascade,
  customer_id uuid references lab_customers (id) on delete cascade,
  kind text not null default 'call' check (kind in ('call', 'visit', 'whatsapp', 'email', 'sample', 'offer', 'note', 'task')),
  notes text check (notes is null or length(notes) <= 2000),
  at timestamptz not null default now(),
  due_date date,                 -- görev / sonraki adım tarihi
  done boolean not null default true,
  created_by uuid default auth.uid(),
  created_at timestamptz not null default now(),
  check (num_nonnulls(lead_id, customer_id) >= 1)
);
create index if not exists crm_activities_lead_idx on crm_activities (lead_id, at desc);
create index if not exists crm_activities_cust_idx on crm_activities (customer_id, at desc);
create index if not exists crm_activities_due_idx on crm_activities (due_date) where not done;

