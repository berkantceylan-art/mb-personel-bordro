-- =====================================================================
-- KALİTE YÖNETİMİ, MEMNUNİYET ANKETİ, MÜŞTERİ İLİŞKİLERİ (CRM)
--  qms_complaints : hekim şikâyeti (ERP, portal ya da düşük anket puanından), kategori, ciddiyet, kök neden, sonuç
--  qms_ncrs       : uygunsuzluk (şikâyet / iç / tedarikçi / denetim), anlık önlem, kök neden
--  qms_actions    : düzeltici / önleyici faaliyetler (sorumlu, termin, etkinlik)
--  qms_audits     : iç denetim kontrol listeleri (madde bazında uygun / değil / not)
--  srv_settings / srv_responses : teslimden N gün sonra tek soruluk anket (bağlantıyla, giriş gerekmez)
--  crm_leads / crm_activities  : potansiyel klinikler, aşamalar, arama / ziyaret / numune kayıtları, sonraki adım
-- Tekrar çalıştırılabilir. Önce 20261226000000_approvals.sql.
-- =====================================================================

create or replace function qms_read() returns boolean language sql stable security definer set search_path = public as $$
  select can_logistics() or can_module('production') or can_module('sales');
$$;
create or replace function qms_write() returns boolean language sql stable security definer set search_path = public as $$
  select can_module('production', 2) or can_module('lab', 2);
$$;

create table if not exists qms_complaints (
  id uuid primary key default gen_random_uuid(),
  company_id uuid references companies (id) on delete cascade default lab_company(),
  no bigint generated by default as identity,
  customer_id uuid references lab_customers (id) on delete set null,
  job_id uuid references jobs (id) on delete set null,
  source text not null default 'phone' check (source in ('phone', 'whatsapp', 'email', 'visit', 'portal', 'survey', 'internal', 'other')),
  category text not null default 'other' check (category in ('fit', 'shade', 'fracture', 'contact', 'occlusion', 'aesthetic', 'delay', 'damage', 'wrong_item', 'billing', 'other')),
  severity text not null default 'medium' check (severity in ('low', 'medium', 'high')),
  description text not null check (length(description) between 1 and 2000),
  status text not null default 'open' check (status in ('open', 'investigating', 'closed')),
  root_cause text check (root_cause is null or length(root_cause) <= 2000),
  resolution text check (resolution is null or length(resolution) <= 2000),
  remake boolean not null default false,
  cost bigint not null default 0 check (cost >= 0),
  owner_id uuid references auth.users (id) on delete set null,
  received_at timestamptz not null default now(),
  closed_at timestamptz,
  created_by uuid default auth.uid(),
  created_at timestamptz not null default now()
);
create index if not exists qms_complaints_idx on qms_complaints (status, received_at desc);
create index if not exists qms_complaints_cust_idx on qms_complaints (customer_id, received_at desc);

create table if not exists qms_ncrs (
  id uuid primary key default gen_random_uuid(),
  company_id uuid references companies (id) on delete cascade default lab_company(),
  no bigint generated by default as identity,
  source text not null default 'internal' check (source in ('complaint', 'internal', 'supplier', 'audit', 'remake')),
  complaint_id uuid references qms_complaints (id) on delete set null,
  title text not null check (length(title) between 1 and 200),
  description text check (description is null or length(description) <= 2000),
  item_id uuid references stk_items (id) on delete set null,
  lot_no text check (lot_no is null or length(lot_no) <= 60),
  immediate_action text check (immediate_action is null or length(immediate_action) <= 1000),
  root_cause text check (root_cause is null or length(root_cause) <= 2000),
  status text not null default 'open' check (status in ('open', 'action', 'verify', 'closed')),
  owner_id uuid references auth.users (id) on delete set null,
  effective boolean,
  closed_at timestamptz,
  created_by uuid default auth.uid(),
  created_at timestamptz not null default now()
);

create table if not exists qms_actions (
  id uuid primary key default gen_random_uuid(),
  ncr_id uuid not null references qms_ncrs (id) on delete cascade,
