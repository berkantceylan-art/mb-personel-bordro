create table if not exists srv_settings (
  company_id uuid primary key references companies (id) on delete cascade default lab_company(),
  enabled boolean not null default false,
  delay_days int not null default 3 check (delay_days between 0 and 30),
  min_days_between int not null default 14 check (min_days_between between 0 and 180),  -- aynı hekime en sık
  updated_at timestamptz not null default now()
);
create table if not exists srv_responses (
  id uuid primary key default gen_random_uuid(),
  company_id uuid references companies (id) on delete cascade default lab_company(),
  customer_id uuid references lab_customers (id) on delete cascade,
  job_id uuid references jobs (id) on delete cascade,
  token text not null unique default encode(gen_random_bytes(16), 'hex'),
  score int check (score is null or score between 1 and 5),
  comment text check (comment is null or length(comment) <= 1000),
  sent_at timestamptz,
  answered_at timestamptz,
  complaint_id uuid references qms_complaints (id) on delete set null,
  created_at timestamptz not null default now()
);
create unique index if not exists srv_responses_job_uidx on srv_responses (job_id);
alter table srv_settings enable row level security;
alter table srv_responses enable row level security;
drop policy if exists srv_settings_read on srv_settings;
create policy srv_settings_read on srv_settings for select to authenticated using (qms_read());
drop policy if exists srv_responses_read on srv_responses;
create policy srv_responses_read on srv_responses for select to authenticated using (qms_read()
  or exists (select 1 from lab_customers c where c.id = customer_id and c.portal_account_id is not null and is_portal_member(c.portal_account_id)));
grant select on srv_settings, srv_responses to authenticated;

create or replace function srv_settings_save(p_enabled boolean, p_delay int, p_between int) returns void
language plpgsql security definer set search_path = public as $$
begin
  if not (can_module('production', 3) or can_module('lab', 3) or can_module('sales', 3)) then raise exception 'not_allowed'; end if;
  insert into srv_settings (company_id, enabled, delay_days, min_days_between, updated_at) values (lab_company(), coalesce(p_enabled, false), coalesce(p_delay, 3), coalesce(p_between, 14), now())
  on conflict (company_id) do update set enabled = excluded.enabled, delay_days = excluded.delay_days, min_days_between = excluded.min_days_between, updated_at = now();
end $$;
revoke execute on function srv_settings_save(boolean, int, int) from public, anon;
grant execute on function srv_settings_save(boolean, int, int) to authenticated;

-- Günlük: teslimden N gün geçmiş işler için anket satırı (hekim başına en sık min_days_between)
create or replace function srv_create_due() returns int
language plpgsql security definer set search_path = public as $$
declare st srv_settings; n int := 0; r record;
begin
  select * into st from srv_settings where company_id = lab_company();
  if st.company_id is null or not st.enabled then return 0; end if;
  for r in
    select distinct on (j.customer_id) j.id, j.customer_id
    from jobs j
    where j.status = 'delivered' and j.customer_id is not null
      and j.delivered_at < now() - make_interval(days => st.delay_days) and j.delivered_at > now() - make_interval(days => st.delay_days + 10)
      and not exists (select 1 from srv_responses s where s.job_id = j.id)
      and not exists (select 1 from srv_responses s where s.customer_id = j.customer_id and s.created_at > now() - make_interval(days => st.min_days_between))
    order by j.customer_id, j.delivered_at desc
  loop
    insert into srv_responses (customer_id, job_id) values (r.customer_id, r.id) on conflict do nothing;
    n := n + 1;
  end loop;
  return n;
end $$;
revoke execute on function srv_create_due() from public, anon, authenticated;
do $$ begin if exists (select 1 from pg_roles where rolname = 'service_role') then
  grant execute on function srv_create_due() to service_role;
end if; end $$;

