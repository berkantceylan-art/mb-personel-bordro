create or replace function crm_lead_from_message(p_message uuid) returns uuid
language plpgsql security definer set search_path = public as $$
declare m cms_messages; v_id uuid;
begin
  if not crm_write() then raise exception 'not_allowed'; end if;
  select * into m from cms_messages where id = p_message;
  if m.id is null then raise exception 'not_found'; end if;
  select id into v_id from crm_leads where message_id = m.id;
  if v_id is not null then return v_id; end if;
  insert into crm_leads (name, contact_name, phone, email, country, source, note, message_id, next_action, next_date)
  values (coalesce(nullif(m.company, ''), m.name), m.name, m.phone, m.email, coalesce(nullif(m.country, ''), 'TR'), 'website', left(m.message, 2000), m.id, 'Geri dön', current_date)
  returning id into v_id;
  return v_id;
end $$;
revoke execute on function crm_lead_from_message(uuid) from public, anon;
grant execute on function crm_lead_from_message(uuid) to authenticated;

-- Günlük: bugün yapılacak CRM adımları için sahibine bildirim
create or replace function crm_due_alerts() returns int
language plpgsql security definer set search_path = public as $$
declare r record; n int := 0;
begin
  for r in
    select owner_id, count(*) c from (
      select owner_id from crm_leads where stage not in ('won', 'lost') and next_date <= current_date and owner_id is not null
      union all
      select created_by from crm_activities where not done and due_date <= current_date and created_by is not null
    ) x group by owner_id
  loop
    perform deliver(lab_company(), array[r.owner_id], 'Bugün ' || r.c || ' müşteri adımı var', 'Arama, ziyaret ve numune takipleri', '/crm');
    n := n + 1;
  end loop;
  return n;
end $$;
revoke execute on function crm_due_alerts() from public, anon, authenticated;
do $$ begin if exists (select 1 from pg_roles where rolname = 'service_role') then
  grant execute on function crm_due_alerts() to service_role;
end if; end $$;

