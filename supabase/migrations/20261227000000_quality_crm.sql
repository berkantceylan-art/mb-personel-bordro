-- Yeni şikâyet → bildirim
create or replace function qms_complaint_notify() returns trigger
language plpgsql security definer set search_path = public as $$
declare v_c text;
begin
  select name into v_c from lab_customers where id = new.customer_id;
  perform deliver(new.company_id, module_recipients('production', 3) || lab_recipients(), 'Şikâyet #' || new.no || case when new.severity = 'high' then ' (yüksek)' else '' end,
                  coalesce(v_c, '') || ': ' || left(new.description, 140), '/kalite?sikayet=' || new.id);
  return new;
exception when others then return new;
end $$;
drop trigger if exists qms_complaint_notify on qms_complaints;
create trigger qms_complaint_notify after insert on qms_complaints for each row execute function qms_complaint_notify();

-- Portaldan şikâyet (hekim kendi vakası için)
create or replace function qms_portal_complaint(p_case uuid, p_category text, p_description text) returns bigint
language plpgsql security definer set search_path = public as $$
declare c portal_cases; v_cust uuid; v_job uuid; v_no bigint;
begin
  select * into c from portal_cases where id = p_case;
  if c.id is null or not is_portal_member(c.account_id) then raise exception 'not_allowed'; end if;
  if nullif(trim(coalesce(p_description, '')), '') is null then raise exception 'description_required'; end if;
  select id into v_cust from lab_customers where portal_account_id = c.account_id limit 1;
  select id into v_job from jobs where portal_case_id = c.id order by created_at desc limit 1;
  insert into qms_complaints (company_id, customer_id, job_id, source, category, description, severity)
  values (lab_company(), v_cust, v_job, 'portal', case when p_category in ('fit', 'shade', 'fracture', 'contact', 'occlusion', 'aesthetic', 'delay', 'damage', 'wrong_item', 'billing', 'other') then p_category else 'other' end,
          left('Vaka #' || c.no || ': ' || trim(p_description), 2000), 'medium')
  returning no into v_no;
  insert into portal_case_events (case_id, kind, body, from_lab, author) values (c.id, 'message', left('Sorun bildirimi: ' || trim(p_description), 4000), false, auth.uid());
  return v_no;
end $$;
revoke execute on function qms_portal_complaint(uuid, text, text) from public, anon;
grant execute on function qms_portal_complaint(uuid, text, text) to authenticated;

