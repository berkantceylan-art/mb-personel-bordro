create or replace function prd_open_jobs() returns table (
  id uuid, no bigint, patient text, doctor_name text, customer_id uuid, customer text, in_date date, due_date date, status text, flow_stage text,
  holder_id uuid, holder text, holder_since timestamptz, qty int, total bigint, currency text, last_action text, last_at timestamptz, last_by text, rejects int
) language sql stable security definer set search_path = public as $$
  select j.id, j.no, j.patient, j.doctor_name, j.customer_id, c.name, j.in_date, j.due_date, j.status, j.flow_stage,
         j.holder_employee_id, he.first_name || ' ' || he.last_name, j.holder_since,
         (select coalesce(sum(i.qty), 0) from job_items i where i.job_id = j.id)::int, j.total, j.currency,
         lh.action, lh.at, le.first_name || ' ' || le.last_name,
         (select count(*) from job_handoffs r where r.job_id = j.id and r.action = 'reject')::int
  from jobs j
  left join lab_customers c on c.id = j.customer_id
  left join employees he on he.id = j.holder_employee_id
  left join lateral (select h.action, h.at, h.employee_id from job_handoffs h where h.job_id = j.id order by h.at desc limit 1) lh on true
  left join employees le on le.id = lh.employee_id
  where j.status not in ('delivered', 'cancelled') and (can_module('production') or can_logistics() or prd_in_flow())
  order by j.due_date nulls last, j.no;
$$;
revoke execute on function prd_open_jobs() from public, anon;
grant execute on function prd_open_jobs() to authenticated;

create or replace function prd_job_timeline(p_job uuid) returns table (at timestamptz, action text, stage text, who text, target text, reason text, minutes int, station text)
language sql stable security definer set search_path = public as $$
  select h.at, h.action, h.stage, e.first_name || ' ' || e.last_name, t.first_name || ' ' || t.last_name, h.reason, h.minutes, s.name
  from job_handoffs h left join employees e on e.id = h.employee_id left join employees t on t.id = h.target_employee_id left join prd_stations s on s.id = h.station_id
  where h.job_id = p_job and (can_module('production') or can_logistics() or prd_in_flow())
  order by h.at;
$$;
revoke execute on function prd_job_timeline(uuid) from public, anon;
grant execute on function prd_job_timeline(uuid) to authenticated;

-- Personel performansı (dönem): alınan / biten iş ve birim, çalışma süresi, geri dönen, onay, çıkış
create or replace function prd_people_stats(p_from timestamptz, p_to timestamptz) returns table (
  employee_id uuid, name text, flow_role text, takes int, dones int, units int, work_minutes int, rejects_received int, rejects_given int, approvals int, exits int,
  holding int, on_time int, finished_jobs int
) language sql stable security definer set search_path = public as $$
  with h as (select * from job_handoffs where at >= p_from and at < p_to),
  ppl as (
    select distinct e.id, e.first_name || ' ' || e.last_name as name, coalesce(p.flow_role, 'technician') as role
    from employees e left join prd_people p on p.employee_id = e.id
    where e.company_id = lab_company() and (p.employee_id is not null or e.id in (select employee_id from h) or e.id in (select target_employee_id from h))
  )
  select ppl.id, ppl.name, ppl.role,
    (select count(*) from h where h.employee_id = ppl.id and h.action = 'take')::int,
    (select count(*) from h where h.employee_id = ppl.id and h.action = 'done')::int,
    (select coalesce(sum(qty), 0) from h where h.employee_id = ppl.id and h.action in ('done', 'approve', 'exit'))::int,
    (select coalesce(sum(minutes), 0) from h where h.employee_id = ppl.id and h.action in ('done', 'approve', 'exit', 'reject'))::int,
    (select count(*) from h where h.target_employee_id = ppl.id and h.action = 'reject')::int,
    (select count(*) from h where h.employee_id = ppl.id and h.action = 'reject')::int,
    (select count(*) from h where h.employee_id = ppl.id and h.action = 'approve')::int,
    (select count(*) from h where h.employee_id = ppl.id and h.action = 'exit')::int,
    (select count(*) from jobs j where j.holder_employee_id = ppl.id and j.status not in ('delivered', 'cancelled'))::int,
    (select count(*) from h join jobs j on j.id = h.job_id where h.employee_id = ppl.id and h.action in ('done', 'approve', 'exit') and (j.due_date is null or (h.at at time zone 'Europe/Istanbul')::date <= j.due_date))::int,
    (select count(*) from h where h.employee_id = ppl.id and h.action in ('done', 'approve', 'exit'))::int
  from ppl
  where can_module('production') or can_logistics()
  order by 6 desc, 2;
