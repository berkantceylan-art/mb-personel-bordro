-- 3) İşi bul (iş no, IS539340, uuid, url, fiş no)
-- ---------------------------------------------------------------------
create or replace function prd_find_job(p_code text) returns jobs
language plpgsql stable security definer set search_path = public as $$
declare v_code text := upper(trim(coalesce(p_code, ''))); j jobs; v_uuid text;
begin
  v_uuid := substring(lower(v_code) from '([0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12})');
  if v_uuid is not null then select * into j from jobs where id = v_uuid::uuid;
  else
    v_code := regexp_replace(v_code, '^(IS|İŞ|IŞ|JOB)[- ]?', '');
    if v_code ~ '^[0-9]{1,12}$' then select * into j from jobs where no = v_code::bigint; end if;
    if j.id is null then select * into j from jobs where upper(slip_no) = v_code order by created_at desc limit 1; end if;
  end if;
  return j;
end $$;
revoke execute on function prd_find_job(text) from public, anon, authenticated;

-- ---------------------------------------------------------------------
-- 4) Okutma
--  p_action: auto | take | done | approve | reject | exit | tryin_out | exit_force
--  sonuç: {job, job_id, patient, customer, due, stage, holder, role, action, qty, options[], warnings[]}
-- ---------------------------------------------------------------------
create or replace function prd_flow_scan(p_code text, p_employee uuid default null, p_action text default 'auto', p_reason text default null, p_target uuid default null) returns jsonb
language plpgsql security definer set search_path = public as $$
declare
  j jobs; v_emp uuid := coalesce(p_employee, prd_my_employee()); pp prd_people; v_role text; v_act text := coalesce(nullif(p_action, ''), 'auto');
  v_qty int; v_min int; v_warn jsonb := '[]'::jsonb; v_opts jsonb := '[]'::jsonb; o prd_job_ops; r jsonb; v_target uuid; v_now timestamptz := now();
  v_holder_name text; v_customer text;
begin
  if not prd_allowed() then raise exception 'not_allowed'; end if;
  if v_emp is null then raise exception 'no_employee'; end if;
  j := prd_find_job(p_code);
  if j.id is null then raise exception 'job_not_found'; end if;
  select * into j from jobs where id = j.id for update;
  if j.status = 'cancelled' then raise exception 'job_cancelled'; end if;
  select * into pp from prd_people where employee_id = v_emp and is_active;
  v_role := coalesce(pp.flow_role, 'technician');
  select greatest(coalesce(sum(qty), 1), 1)::int into v_qty from job_items where job_id = j.id;
  v_min := case when j.holder_employee_id = v_emp and j.holder_since is not null then greatest(0, extract(epoch from v_now - j.holder_since) / 60)::int end;

  if j.status = 'delivered' and v_act not in ('note') then
    -- teslim edilmiş iş geri geldiyse (tamir / ayar) üretime alınabilir: yalnız take
    if v_act <> 'take' then raise exception 'already_out'; end if;
  end if;

  -- otomatik karar
  if v_act = 'auto' then
    if j.holder_employee_id is distinct from v_emp then v_act := 'take';
    elsif v_role = 'technician' then v_act := 'done';
    else v_act := 'hold';   -- şef / kontrol / pazarlama: elindeyse seçenek göster
    end if;
  end if;

  if v_act = 'take' then
    if j.status = 'delivered' then
      raise exception 'already_out';
    end if;
    insert into job_handoffs (job_id, employee_id, action, stage, station_id, qty)
    values (j.id, v_emp, 'take', case v_role when 'chief' then 'chief' when 'qc' then 'qc' when 'dispatch' then 'dispatch' else 'production' end, pp.station_id, v_qty);
    update jobs set holder_employee_id = v_emp, holder_since = v_now,
      flow_stage = case v_role when 'chief' then 'chief' when 'qc' then 'qc' when 'dispatch' then 'dispatch' else 'production' end,
      status = case when status = 'tryin' then 'open' else status end
    where id = j.id;
    if v_role = 'qc' and j.chief_passed_at is null then v_warn := v_warn || '"Şef kontrolünden geçmemiş"'::jsonb; end if;
    if v_role = 'dispatch' and j.qc_passed_at is null then v_warn := v_warn || '"Kalite kontrolden geçmemiş: çıkış yapılamaz"'::jsonb; end if;
    -- istasyon adımı varsa başlat
    if v_role = 'technician' and pp.station_id is not null then
      perform prd_plan(j.id);
      select * into o from prd_job_ops where job_id = j.id and station_id = pp.station_id and round = (select max(round) from prd_job_ops where job_id = j.id);
      if o.id is not null and o.status in ('waiting', 'ready', 'paused') then perform prd_op_action(o.id, 'start', v_emp, null); end if;
    end if;

  elsif v_act = 'done' then
    if j.holder_employee_id is distinct from v_emp then raise exception 'not_holder'; end if;
    insert into job_handoffs (job_id, employee_id, action, stage, station_id, minutes, qty) values (j.id, v_emp, 'done', j.flow_stage, pp.station_id, v_min, v_qty);
    update jobs set holder_employee_id = null, holder_since = v_now where id = j.id;
    if pp.station_id is not null then
      select * into o from prd_job_ops where job_id = j.id and station_id = pp.station_id and round = (select max(round) from prd_job_ops where job_id = j.id);
      if o.id is not null and o.status in ('in_progress', 'paused', 'ready', 'waiting') then
        r := prd_op_action(o.id, 'finish', v_emp, null);
        if jsonb_array_length(coalesce(r->'warnings', '[]'::jsonb)) > 0 then
          v_warn := v_warn || (select coalesce(jsonb_agg(to_jsonb('Stok yetersiz: ' || (w->>'item') || ' ' || (w->>'missing') || ' ' || (w->>'unit'))), '[]'::jsonb) from jsonb_array_elements(r->'warnings') w);
        end if;
      end if;
    end if;

  elsif v_act = 'approve' then
    if v_role not in ('chief', 'qc') then raise exception 'role_required'; end if;
    if j.holder_employee_id is distinct from v_emp then raise exception 'not_holder'; end if;
    insert into job_handoffs (job_id, employee_id, action, stage, minutes, qty) values (j.id, v_emp, 'approve', v_role, v_min, v_qty);
    update jobs set holder_employee_id = null, holder_since = v_now,
      chief_passed_at = case when v_role = 'chief' then v_now else chief_passed_at end,
      qc_passed_at = case when v_role = 'qc' then v_now else qc_passed_at end,
      flow_stage = case when v_role = 'chief' then 'qc' else 'dispatch' end
    where id = j.id;

  elsif v_act = 'reject' then
    if v_role not in ('chief', 'qc', 'dispatch') then raise exception 'role_required'; end if;
    if nullif(trim(coalesce(p_reason, '')), '') is null then raise exception 'reason_required'; end if;
    -- varsayılan: işi en son bitiren teknisyen
    v_target := coalesce(p_target, (select h.employee_id from job_handoffs h left join prd_people x on x.employee_id = h.employee_id
                                     where h.job_id = j.id and h.action = 'done' and coalesce(x.flow_role, 'technician') = 'technician' order by h.at desc limit 1));
    insert into job_handoffs (job_id, employee_id, action, stage, target_employee_id, reason, minutes, qty)
    values (j.id, v_emp, 'reject', v_role, v_target, left(p_reason, 300), v_min, v_qty);
    update jobs set holder_employee_id = null, holder_since = v_now, flow_stage = 'production',
      chief_passed_at = null, qc_passed_at = case when v_role = 'dispatch' then qc_passed_at else null end
    where id = j.id;

  elsif v_act in ('exit', 'exit_force') then
    if v_role <> 'dispatch' and not can_module('production', 3) then raise exception 'role_required'; end if;
    if j.qc_passed_at is null and not (v_act = 'exit_force' and can_module('production', 3)) then raise exception 'qc_required'; end if;
    insert into job_handoffs (job_id, employee_id, action, stage, minutes, qty, reason) values (j.id, v_emp, 'exit', 'dispatch', v_min, v_qty, case when v_act = 'exit_force' then 'Kalite kontrolsüz çıkış (yönetici)' end);
    update jobs set holder_employee_id = null, holder_since = v_now, flow_stage = 'out', status = 'delivered', delivered_at = v_now where id = j.id;

  elsif v_act = 'tryin_out' then
    if v_role <> 'dispatch' and not can_module('production', 3) then raise exception 'role_required'; end if;
    insert into job_handoffs (job_id, employee_id, action, stage, minutes, qty) values (j.id, v_emp, 'tryin_out', 'dispatch', v_min, v_qty);
    update jobs set holder_employee_id = null, holder_since = v_now, flow_stage = 'tryin', status = 'tryin', chief_passed_at = null, qc_passed_at = null where id = j.id;

  elsif v_act = 'hold' then
    null;
  else
    raise exception 'bad_action';
  end if;

  select * into j from jobs where id = j.id;
  if j.holder_employee_id = v_emp then
    v_opts := case v_role when 'technician' then '["done"]' when 'chief' then '["approve","reject"]' when 'qc' then '["approve","reject"]'
                          when 'dispatch' then case when j.qc_passed_at is not null then '["exit","tryin_out","reject"]' else '["tryin_out","reject"]' end else '[]' end::jsonb;
  end if;
  select e.first_name || ' ' || e.last_name into v_holder_name from employees e where e.id = j.holder_employee_id;
  select c.name into v_customer from lab_customers c where c.id = j.customer_id;
  return jsonb_build_object('job', j.no, 'job_id', j.id, 'patient', j.patient, 'customer', v_customer, 'doctor', j.doctor_name, 'due', j.due_date,
                            'stage', j.flow_stage, 'status', j.status, 'holder', v_holder_name, 'role', v_role, 'action', v_act, 'qty', v_qty,
                            'options', v_opts, 'warnings', v_warn, 'minutes', v_min);
end $$;
revoke execute on function prd_flow_scan(text, uuid, text, text, uuid) from public, anon;
grant execute on function prd_flow_scan(text, uuid, text, text, uuid) to authenticated;

-- ---------------------------------------------------------------------
-- 5) İş durumu elle değişirse akış da uyumlu kalsın (ör. "Teslim edildi" düğmesi)
-- ---------------------------------------------------------------------
create or replace function jobs_flow_sync() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  if new.status is distinct from old.status then
    if new.status = 'delivered' and new.flow_stage <> 'out' then
      new.flow_stage := 'out'; new.holder_employee_id := null; new.holder_since := now();
      insert into job_handoffs (job_id, employee_id, action, stage, reason) values (new.id, prd_my_employee(), 'exit', 'dispatch', 'İş kaydından teslim edildi');
    elsif new.status = 'tryin' and new.flow_stage <> 'tryin' then
      new.flow_stage := 'tryin'; new.holder_employee_id := null; new.holder_since := now();
      insert into job_handoffs (job_id, employee_id, action, stage, reason) values (new.id, prd_my_employee(), 'tryin_out', 'dispatch', 'İş kaydından provaya');
    elsif new.status = 'cancelled' then
      new.holder_employee_id := null;
    elsif old.status in ('delivered', 'tryin', 'cancelled') and new.status in ('open', 'ready') and new.flow_stage in ('out', 'tryin') then
      new.flow_stage := 'production'; new.holder_since := now();
    end if;
  end if;
  return new;
end $$;
drop trigger if exists jobs_flow_sync on jobs;
create trigger jobs_flow_sync before update of status on jobs for each row execute function jobs_flow_sync();

