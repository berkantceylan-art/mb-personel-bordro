create or replace function prd_in_flow() returns boolean language sql stable security definer set search_path = public as $$
  select exists (select 1 from prd_people p join employees e on e.id = p.employee_id where e.user_id = auth.uid() and p.is_active);
$$;
grant execute on function prd_in_flow() to authenticated;

-- akışta olan personele üretim modülünde en az "düzenler" yetkisi
create or replace function module_level(p_module text) returns smallint
language sql stable security definer set search_path = public as $$
  select greatest(
    coalesce(
      (select p.level from module_permissions p join memberships m on m.company_id = p.company_id and m.user_id = p.user_id
       where p.user_id = auth.uid() and p.module = p_module order by m.created_at limit 1),
      (select module_default_level(m.role::text, m.logistics_access, p_module) from memberships m where m.user_id = auth.uid() order by m.created_at limit 1),
      0::smallint),
    case when p_module = 'production' and prd_in_flow() then 2 else 0 end
  )::smallint;
$$;
grant execute on function module_level(text) to authenticated;

create or replace function prd_allowed() returns boolean language sql stable security definer set search_path = public as $$
  select can_module('production', 2) or can_logistics() or prd_in_flow();
$$;

