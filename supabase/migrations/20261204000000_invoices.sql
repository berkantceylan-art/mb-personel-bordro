-- ---------------------------------------------------------------------
-- Cari bul / aç (VKN-TCKN, yoksa ad)
--   p: {name, tax_no, tax_office, address, district, city, country, email, phone, website, einvoice_alias, is_einvoice, currency}
--   p_role: customer | supplier
-- ---------------------------------------------------------------------
create or replace function fin_party_ensure(p jsonb, p_role text) returns uuid
language plpgsql security definer set search_path = public as $$
declare v_tax text; v_id uuid; v_kind text; v_name text := left(trim(coalesce(p->>'name', '')), 200);
begin
  if not (can_module('sales', 2) or can_module('purchases', 2) or can_module('finance', 2)) then raise exception 'not_allowed'; end if;
  if p_role not in ('customer', 'supplier') then raise exception 'bad_role'; end if;
  v_tax := nullif(regexp_replace(coalesce(p->>'tax_no', ''), '\D', '', 'g'), '');
  if v_tax is not null and length(v_tax) not in (10, 11) then v_tax := null; end if;
  if v_tax is not null then
    select id, kind into v_id, v_kind from fin_parties where company_id = lab_company() and tax_no = v_tax limit 1;
  end if;
  if v_id is null and v_name <> '' then
    select id, kind into v_id, v_kind from fin_parties
    where company_id = lab_company() and lower(name) = lower(v_name) and (v_tax is null or tax_no is null) order by created_at limit 1;
  end if;
  if v_id is not null then
    update fin_parties set
      kind = case when kind = p_role or kind = 'both' then kind when kind = 'other' then p_role else 'both' end,
      tax_no = coalesce(tax_no, v_tax),
      tax_office = coalesce(tax_office, nullif(left(p->>'tax_office', 80), '')),
      address = coalesce(address, nullif(left(p->>'address', 400), '')),
      district = coalesce(district, nullif(left(p->>'district', 80), '')),
      city = coalesce(city, nullif(left(p->>'city', 80), '')),
      email = coalesce(email, nullif(left(p->>'email', 200), '')),
      phone = coalesce(phone, nullif(left(p->>'phone', 40), '')),
      website = coalesce(website, nullif(left(p->>'website', 200), '')),
      einvoice_alias = coalesce(einvoice_alias, nullif(left(p->>'einvoice_alias', 120), '')),
      is_einvoice = is_einvoice or coalesce((p->>'is_einvoice')::boolean, false)
    where id = v_id;
    return v_id;
  end if;
  if v_name = '' then raise exception 'party_name_required'; end if;
  insert into fin_parties (name, kind, person_type, tax_no, tax_office, address, district, city, country, email, phone, website, einvoice_alias, is_einvoice, currency, source)
  values (v_name, p_role, case when length(coalesce(v_tax, '')) = 11 then 'person' else 'company' end, v_tax,
          nullif(left(p->>'tax_office', 80), ''), nullif(left(p->>'address', 400), ''), nullif(left(p->>'district', 80), ''), nullif(left(p->>'city', 80), ''),
          coalesce(nullif(left(p->>'country', 60), ''), 'TR'), nullif(left(p->>'email', 200), ''), nullif(left(p->>'phone', 40), ''),
          nullif(left(p->>'website', 200), ''), nullif(left(p->>'einvoice_alias', 120), ''), coalesce((p->>'is_einvoice')::boolean, false),
          case when p->>'currency' in ('TRY', 'EUR', 'USD', 'GBP', 'CHF') then p->>'currency' else 'TRY' end,
          coalesce(nullif(p->>'source', ''), 'einvoice'))
  returning id into v_id;
  return v_id;
end $$;
revoke execute on function fin_party_ensure(jsonb, text) from public, anon;
grant execute on function fin_party_ensure(jsonb, text) to authenticated;

-- ---------------------------------------------------------------------
-- Taslak kaydet
-- ---------------------------------------------------------------------
create or replace function inv_save(p jsonb) returns uuid
language plpgsql security definer set search_path = public as $$
declare
  v_id uuid := nullif(p->>'id', '')::uuid;
  v_dir text := p->>'direction';
  v_old inv_invoices;
  pt fin_parties;
  v_cur text := coalesce(nullif(p->>'currency', ''), 'TRY');
  v_date date := coalesce(nullif(p->>'invoice_date', '')::date, current_date);
  v_rate numeric;
  v_profile text;
  l jsonb; i int := 0;
  v_qty numeric; v_price numeric; v_disc numeric; v_vr numeric; v_wr numeric;
  v_gross bigint; v_discount bigint; v_net bigint; v_vat bigint; v_wh bigint;
begin
  if v_dir not in ('sale', 'purchase') then raise exception 'bad_direction'; end if;
  if not can_module(inv_module(v_dir), 2) then raise exception 'not_allowed'; end if;
  if v_id is not null then
    select * into v_old from inv_invoices where id = v_id for update;
    if v_old.id is null then raise exception 'not_found'; end if;
    if v_old.status <> 'draft' or v_old.direction <> v_dir then raise exception 'bad_status'; end if;
  end if;
  select * into pt from fin_parties where id = nullif(p->>'party_id', '')::uuid;
  if pt.id is null then raise exception 'party_required'; end if;
  if jsonb_typeof(p->'lines') <> 'array' or jsonb_array_length(p->'lines') = 0 then raise exception 'lines_required'; end if;
  v_rate := case when v_cur = 'TRY' then 1 else coalesce(nullif(p->>'rate', '')::numeric, fx_rate(v_cur, v_date)) end;
  if v_rate is null or v_rate <= 0 then raise exception 'rate_missing:%', v_cur; end if;
  v_profile := coalesce(nullif(p->>'profile', ''),
                        case when v_dir = 'purchase' then 'TICARIFATURA' when pt.country not in ('TR', 'Türkiye', 'Turkey') then 'IHRACAT' when pt.is_einvoice then 'TICARIFATURA' else 'EARSIVFATURA' end);

  if v_id is null then
    insert into inv_invoices (direction, party_id) values (v_dir, pt.id) returning id into v_id;
  end if;
  update inv_invoices set
    type = case when p->>'type' = 'return' then 'return' else 'invoice' end,
    doc_no = nullif(upper(left(trim(coalesce(p->>'doc_no', '')), 40)), ''),
    ettn = coalesce(nullif(p->>'ettn', '')::uuid, ettn),
    profile = v_profile,
    invoice_date = v_date,
    invoice_time = nullif(p->>'invoice_time', '')::time,
    due_date = coalesce(nullif(p->>'due_date', '')::date, v_date + pt.payment_term_days),
    party_id = pt.id, party_name = pt.name, party_tax_no = pt.tax_no, party_tax_office = pt.tax_office, party_address = pt.address,
    party_district = pt.district, party_city = pt.city, party_country = pt.country, party_email = pt.email,
    currency = v_cur, rate = v_rate,
    warehouse_id = coalesce(nullif(p->>'warehouse_id', '')::uuid, stk_default_warehouse()),
    -- düzenlemede gönderilmeyen alanlar korunur; iade faturası asıl faturanın bakiye davranışını alır
    affects_balance = coalesce((p->>'affects_balance')::boolean, v_old.affects_balance,
                               (select o.affects_balance from inv_invoices o where o.id = nullif(p->>'return_of', '')::uuid), true),
    job_ids = case when p ? 'job_ids' then coalesce((select array_agg(x::uuid) from jsonb_array_elements_text(p->'job_ids') x), '{}') else coalesce(v_old.job_ids, '{}') end,
    return_of = coalesce(nullif(p->>'return_of', '')::uuid, v_old.return_of),
    source = coalesce(nullif(p->>'source', ''), source),
    einvoice_status = coalesce(nullif(p->>'einvoice_status', ''), einvoice_status),
    ubl_xml = coalesce(nullif(p->>'ubl_xml', ''), ubl_xml),
    note = nullif(left(coalesce(p->>'note', ''), 1000), '')
  where id = v_id;

  delete from inv_lines where invoice_id = v_id;
  for l in select * from jsonb_array_elements(p->'lines') loop
    v_qty := coalesce(nullif(l->>'qty', '')::numeric, 0);
    if v_qty <= 0 then continue; end if;
    v_price := greatest(coalesce(nullif(l->>'unit_price', '')::numeric, 0), 0);
    v_disc := least(greatest(coalesce(nullif(l->>'discount_pct', '')::numeric, 0), 0), 100);
    v_vr := least(greatest(coalesce(nullif(l->>'vat_rate', '')::numeric, 0), 0), 100);
    v_wr := least(greatest(coalesce(nullif(l->>'withholding_rate', '')::numeric, 0), 0), 100);
    v_gross := round(v_qty * v_price * 100);
    v_net := round(v_gross * (100 - v_disc) / 100);
    v_discount := v_gross - v_net;
    v_vat := round(v_net * v_vr / 100);
    v_wh := round(v_vat * v_wr / 100);
    i := i + 1;
    insert into inv_lines (invoice_id, sort, item_id, lab_product_id, category_id, job_id, name, seller_code, qty, unit, unit_price, discount_pct, vat_rate, withholding_rate,
                           withholding_code, vat_exemption_code, lot_no, expiry_date, gross, discount, net, vat, withholding, total)
    values (v_id, i, nullif(l->>'item_id', '')::uuid, nullif(l->>'lab_product_id', '')::uuid, nullif(l->>'category_id', '')::uuid, nullif(l->>'job_id', '')::uuid,
            left(coalesce(nullif(trim(l->>'name'), ''), 'Kalem'), 300), nullif(left(l->>'seller_code', 60), ''), v_qty, left(coalesce(nullif(l->>'unit', ''), 'adet'), 20),
            v_price, v_disc, v_vr, v_wr,
            case when v_wr > 0 and l->>'withholding_code' ~ '^[0-9]{3}$' then l->>'withholding_code' end,
            case when v_vr = 0 and l->>'vat_exemption_code' ~ '^[0-9]{3}$' then l->>'vat_exemption_code' end,
            nullif(left(trim(coalesce(l->>'lot_no', '')), 60), ''), nullif(l->>'expiry_date', '')::date,
            v_gross, v_discount, v_net, v_vat, v_wh, v_net + v_vat);
  end loop;
  if i = 0 then raise exception 'lines_required'; end if;
  update inv_invoices v set
    gross_total = s.g, discount_total = s.d, subtotal = s.n, vat_total = s.v, withholding_total = s.w, total = s.n + s.v - s.w
  from (select coalesce(sum(gross), 0) g, coalesce(sum(discount), 0) d, coalesce(sum(net), 0) n, coalesce(sum(vat), 0) v, coalesce(sum(withholding), 0) w
        from inv_lines where invoice_id = v_id) s
  where v.id = v_id;
  return v_id;
end $$;
revoke execute on function inv_save(jsonb) from public, anon;
grant execute on function inv_save(jsonb) to authenticated;

create or replace function inv_delete(p_id uuid) returns void
language plpgsql security definer set search_path = public as $$
declare v inv_invoices;
begin
  select * into v from inv_invoices where id = p_id for update;
  if v.id is null then return; end if;
  if not can_module(inv_module(v.direction), 2) then raise exception 'not_allowed'; end if;
  if v.status <> 'draft' then raise exception 'bad_status'; end if;
  delete from inv_invoices where id = p_id;
end $$;
revoke execute on function inv_delete(uuid) from public, anon;
grant execute on function inv_delete(uuid) to authenticated;

-- ---------------------------------------------------------------------
