create table if not exists inv_invoices (
  id uuid primary key default gen_random_uuid(),
  company_id uuid references companies (id) on delete cascade default lab_company(),
  no bigint generated by default as identity,
  direction text not null check (direction in ('sale', 'purchase')),
  type text not null default 'invoice' check (type in ('invoice', 'return')),
  status text not null default 'draft' check (status in ('draft', 'posted', 'cancelled')),
  doc_no text check (doc_no is null or length(doc_no) <= 40),             -- fatura numarası
  ettn uuid not null default gen_random_uuid(),                            -- e-fatura UUID
  profile text not null default 'TICARIFATURA' check (profile in ('TEMELFATURA', 'TICARIFATURA', 'EARSIVFATURA', 'IHRACAT', 'KAGIT')),
  invoice_date date not null default current_date,
  invoice_time time,
  due_date date,
  party_id uuid not null references fin_parties (id) on delete restrict,
  party_name text, party_tax_no text, party_tax_office text, party_address text, party_district text, party_city text, party_country text, party_email text,
  currency text not null default 'TRY' check (currency in ('TRY', 'EUR', 'USD', 'GBP', 'CHF')),
  rate numeric(18, 6) not null default 1 check (rate > 0),
  warehouse_id uuid references stk_warehouses (id) on delete set null,
  gross_total bigint not null default 0,          -- iskonto öncesi
  discount_total bigint not null default 0,
  subtotal bigint not null default 0,             -- matrah (iskonto sonrası)
  vat_total bigint not null default 0,
  withholding_total bigint not null default 0,    -- KDV tevkifatı
  total bigint not null default 0,                -- ödenecek tutar
  affects_balance boolean not null default true,  -- false: işlerden kesilen fatura (iş tutarı cari bakiyede zaten var, yalnız KDV eklenir)
  job_ids uuid[] not null default '{}',
  return_of uuid references inv_invoices (id) on delete set null,
  einvoice_status text not null default 'none' check (einvoice_status in ('none', 'ready', 'sent', 'accepted', 'rejected', 'imported')),
  einvoice_note text check (einvoice_note is null or length(einvoice_note) <= 500),
  ubl_xml text check (ubl_xml is null or length(ubl_xml) <= 3000000),
  source text not null default 'manual' check (source in ('manual', 'ubl', 'jobs')),
  fin_txn_id uuid references fin_txns (id) on delete set null,
  note text check (note is null or length(note) <= 1000),
  created_by uuid default auth.uid(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  posted_at timestamptz, posted_by uuid,
  cancelled_at timestamptz, cancelled_by uuid,
  cancel_reason text check (cancel_reason is null or length(cancel_reason) <= 300)
);
