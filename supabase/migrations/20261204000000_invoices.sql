-- Fatura numarası serisi: ABC2026000000001 (GİB biçimi: 3 harf + yıl + 9 hane)
create table if not exists inv_series (
  company_id uuid not null references companies (id) on delete cascade,
  prefix text not null check (prefix ~ '^[A-Z0-9]{3}$'),
  year int not null,
  last_no bigint not null default 0,
  primary key (company_id, prefix, year)
);
alter table inv_series enable row level security;
drop policy if exists inv_series_read on inv_series;
create policy inv_series_read on inv_series for select to authenticated using (can_module('sales'));
grant select on inv_series to authenticated;

create or replace function inv_next_no(p_prefix text, p_year int) returns text
language plpgsql security definer set search_path = public as $$
declare v bigint;
begin
  insert into inv_series (company_id, prefix, year, last_no) values (lab_company(), p_prefix, p_year, 1)
  on conflict (company_id, prefix, year) do update set last_no = inv_series.last_no + 1
  returning last_no into v;
  return p_prefix || p_year::text || lpad(v::text, 9, '0');
end $$;
revoke execute on function inv_next_no(text, int) from public, anon, authenticated;

