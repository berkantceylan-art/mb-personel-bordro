-- ---------------------------------------------------------------------
create or replace function inv_post(p_id uuid) returns uuid
language plpgsql security definer set search_path = public as $$
declare
  v inv_invoices; pt fin_parties; co companies; l record; it stk_items;
  s int;                     -- +1: cari bize borçlanır (satış faturası, alış iadesi)
  v_lines jsonb := '[]'::jsonb;
  v_party_rate numeric; v_party_amt bigint; v_base bigint;
  v_cogs bigint := 0; v_cost bigint; v_have numeric;
  v_txn uuid; v_kind text; v_wh uuid; v_note text;
  c record;
begin
  select * into v from inv_invoices where id = p_id for update;
  if v.id is null then raise exception 'not_found'; end if;
  if not can_module(inv_module(v.direction), 2) then raise exception 'not_allowed'; end if;
  if v.status <> 'draft' then raise exception 'bad_status'; end if;
  if v.total <= 0 then raise exception 'empty_invoice'; end if;
  select * into pt from fin_parties where id = v.party_id;
  select * into co from companies where id = coalesce(v.company_id, lab_company());

  -- satış faturasına numara
  if v.direction = 'sale' and v.doc_no is null and v.profile <> 'KAGIT' then
    v.doc_no := inv_next_no(case when v.profile = 'EARSIVFATURA' then co.inv_prefix_earsiv else co.inv_prefix_efatura end, extract(year from v.invoice_date)::int);
    update inv_invoices set doc_no = v.doc_no where id = v.id;
  end if;

  s := case when (v.direction = 'sale') = (v.type = 'invoice') then 1 else -1 end;
  v_kind := case when v.direction = 'sale' then (case when v.type = 'invoice' then 'sale_invoice' else 'sale_return' end)
                 else (case when v.type = 'invoice' then 'purchase_invoice' else 'purchase_return' end) end;
  v_wh := coalesce(v.warehouse_id, stk_default_warehouse());
  v_note := coalesce(v.doc_no, 'Fatura #' || v.no) || ' · ' || coalesce(v.party_name, pt.name);

  -- stok hareketleri ve satılan malın maliyeti
  for l in select * from inv_lines where invoice_id = v.id and item_id is not null order by sort loop
    select * into it from stk_items where id = l.item_id;
    if it.id is null or it.kind = 'service' then continue; end if;
    if v.direction = 'sale' and v.type = 'invoice' then
      select coalesce(sum(qty), 0) into v_have from stk_moves where item_id = it.id and warehouse_id = v_wh and (l.lot_no is null or lot_no = l.lot_no);
      if v_have < l.qty then raise exception 'insufficient:%', it.name || ' (' || v_have || ' ' || it.unit || ')'; end if;
      v_cost := round(l.qty * stk_avg_cost(it.id));
      if l.lot_no is not null then
        perform stk_move_sys(it.id, v_wh, -l.qty, 'sale', null, l.lot_no, l.expiry_date, v.invoice_date, 'invoice', v.id, null, v.party_id, v_note);
      else
        perform stk_consume_fifo(it.id, v_wh, l.qty, 'sale', v.invoice_date, 'invoice', v.id, null, v_note);
      end if;
      v_cogs := v_cogs + v_cost;
    elsif v.direction = 'sale' then   -- satış iadesi: ortalama maliyetle geri girer
      v_cost := round(l.qty * stk_avg_cost(it.id));
      perform stk_move_sys(it.id, v_wh, l.qty, 'sale_return', stk_avg_cost(it.id), l.lot_no, l.expiry_date, v.invoice_date, 'invoice', v.id, null, v.party_id, v_note);
      v_cogs := v_cogs - v_cost;
    elsif v.type = 'invoice' then     -- alış: birim maliyet = iskontolu matrah (TL) / miktar
      perform stk_move_sys(it.id, v_wh, l.qty, 'purchase', round(l.net * v.rate / l.qty)::bigint, l.lot_no, l.expiry_date, v.invoice_date, 'invoice', v.id, null, v.party_id, v_note);
      if it.purchase_price is distinct from round(l.net / l.qty)::bigint or it.purchase_currency <> v.currency then
        update stk_items set purchase_price = round(l.net / l.qty)::bigint, purchase_currency = v.currency,
                             supplier_party_id = coalesce(supplier_party_id, v.party_id) where id = it.id;
      end if;
    else                              -- alış iadesi
      select coalesce(sum(qty), 0) into v_have from stk_moves where item_id = it.id and warehouse_id = v_wh;
      if v_have < l.qty then raise exception 'insufficient:%', it.name || ' (' || v_have || ' ' || it.unit || ')'; end if;
      if l.lot_no is not null then
        perform stk_move_sys(it.id, v_wh, -l.qty, 'purchase_return', null, l.lot_no, null, v.invoice_date, 'invoice', v.id, null, v.party_id, v_note);
      else
        perform stk_consume_fifo(it.id, v_wh, l.qty, 'purchase_return', v.invoice_date, 'invoice', v.id, null, v_note);
      end if;
    end if;
  end loop;

  -- finans satırları
  if v.affects_balance then
    v_party_rate := case when pt.currency = 'TRY' then 1 when pt.currency = v.currency then v.rate else fx_rate(pt.currency, v.invoice_date) end;
    if v_party_rate is null then raise exception 'rate_missing:%', pt.currency; end if;
    v_party_amt := case when pt.currency = v.currency then v.total else round(v.total * v.rate / v_party_rate) end;
    v_lines := v_lines || jsonb_build_object('party_id', pt.id, 'amount', s * v_party_amt, 'currency', pt.currency, 'rate', v_party_rate);
    -- gelir / gider / stok hesapları (kategori bazında)
    for c in
      select coalesce(li.category_id,
               case when v.direction = 'sale' then
                      fin_category(case when li.lab_product_id is not null or li.job_id is not null or si.kind = 'product' then 'sales_prosthesis' else 'sales_goods' end)
                    else fin_category(case when si.kind is not null and si.kind <> 'service' then 'stock' when si.kind = 'service' then 'exp_other' else 'exp_material' end) end) as cat,
             sum(li.net) as net
      from inv_lines li left join stk_items si on si.id = li.item_id
      where li.invoice_id = v.id group by 1
    loop
      v_lines := v_lines || jsonb_build_object('category_id', c.cat, 'amount', -s * c.net, 'currency', v.currency, 'rate', v.rate);
    end loop;
  else
    -- işlerden kesilen fatura: iş tutarı hekim bakiyesinde zaten var → yalnız KDV cariye eklenir
    v_party_rate := case when pt.currency = 'TRY' then 1 when pt.currency = v.currency then v.rate else fx_rate(pt.currency, v.invoice_date) end;
    if v_party_rate is null then raise exception 'rate_missing:%', pt.currency; end if;
    v_base := v.vat_total - v.withholding_total;
    v_lines := v_lines || jsonb_build_object('party_id', pt.id, 'amount', s * (case when pt.currency = v.currency then v_base else round(v_base * v.rate / v_party_rate) end), 'currency', pt.currency, 'rate', v_party_rate);
  end if;
  if v.vat_total - v.withholding_total <> 0 then
    v_lines := v_lines || jsonb_build_object('category_id', fin_category(case when v.direction = 'sale' then 'vat_out' else 'vat_in' end),
                                             'amount', -s * (v.vat_total - v.withholding_total), 'currency', v.currency, 'rate', v.rate);
  end if;
  if v_cogs <> 0 then
    v_lines := v_lines || jsonb_build_object('category_id', fin_category('cogs'), 'amount', v_cogs, 'currency', 'TRY', 'rate', 1, 'description', 'Satılan malın maliyeti')
                       || jsonb_build_object('category_id', fin_category('stock'), 'amount', -v_cogs, 'currency', 'TRY', 'rate', 1, 'description', 'Stoktan çıkış');
  end if;

  v_txn := fin_post_sys(
    jsonb_build_object('kind', v_kind, 'txn_date', v.invoice_date, 'description', v_note, 'doc_no', v.doc_no, 'amount', v.total, 'currency', v.currency,
                       'party_id', pt.id, 'ref_type', 'invoice', 'ref_id', v.id),
    v_lines);

  update inv_invoices set status = 'posted', fin_txn_id = v_txn, posted_at = now(), posted_by = auth.uid(),
    einvoice_status = case when einvoice_status = 'none' and direction = 'sale' and profile <> 'KAGIT' then 'ready' else einvoice_status end
  where id = v.id;
  if array_length(v.job_ids, 1) > 0 then
    update jobs set invoice_id = v.id where id = any (v.job_ids);
  end if;
  return v.id;
end $$;
revoke execute on function inv_post(uuid) from public, anon;
grant execute on function inv_post(uuid) to authenticated;

-- ---------------------------------------------------------------------
-- İptal
-- ---------------------------------------------------------------------
create or replace function inv_cancel(p_id uuid, p_reason text) returns void
language plpgsql security definer set search_path = public as $$
declare v inv_invoices;
begin
  select * into v from inv_invoices where id = p_id for update;
  if v.id is null then raise exception 'not_found'; end if;
  if not can_module(inv_module(v.direction), 3) then raise exception 'not_allowed'; end if;
  if v.status <> 'posted' then raise exception 'bad_status'; end if;
  if v.direction = 'sale' and v.einvoice_status in ('sent', 'accepted') then raise exception 'einvoice_sent'; end if;
  if v.fin_txn_id is not null then
    update fin_txns set voided_at = now(), voided_by = auth.uid(), void_reason = left('Fatura iptali: ' || coalesce(p_reason, ''), 300)
    where id = v.fin_txn_id and voided_at is null;
  end if;
  delete from stk_moves where doc_type = 'invoice' and doc_id = v.id;
  update jobs set invoice_id = null where invoice_id = v.id;
  update inv_invoices set status = 'cancelled', cancelled_at = now(), cancelled_by = auth.uid(), cancel_reason = left(coalesce(p_reason, ''), 300) where id = v.id;
end $$;
revoke execute on function inv_cancel(uuid, text) from public, anon;
grant execute on function inv_cancel(uuid, text) to authenticated;

-- e-fatura durumu (entegratör portalından gönderildi / kabul / red)
create or replace function inv_set_einvoice(p_id uuid, p_status text, p_note text, p_doc_no text default null) returns void
language plpgsql security definer set search_path = public as $$
declare v inv_invoices;
begin
  select * into v from inv_invoices where id = p_id for update;
  if v.id is null then raise exception 'not_found'; end if;
  if not can_module(inv_module(v.direction), 2) then raise exception 'not_allowed'; end if;
  if p_status not in ('none', 'ready', 'sent', 'accepted', 'rejected', 'imported') then raise exception 'bad_status'; end if;
  update inv_invoices set einvoice_status = p_status, einvoice_note = nullif(left(coalesce(p_note, ''), 500), ''),
    doc_no = coalesce(nullif(upper(trim(coalesce(p_doc_no, ''))), ''), doc_no)
  where id = p_id;
end $$;
revoke execute on function inv_set_einvoice(uuid, text, text, text) from public, anon;
grant execute on function inv_set_einvoice(uuid, text, text, text) to authenticated;

-- ---------------------------------------------------------------------
-- Laboratuvar işlerinden satış faturası taslağı
-- ---------------------------------------------------------------------
create or replace function inv_from_jobs(p_jobs uuid[]) returns uuid
language plpgsql security definer set search_path = public as $$
declare
  v_customers int; v_curs int; v_customer uuid; v_cur text; v_party uuid; v_vat numeric;
  v_lines jsonb := '[]'::jsonb; j record; li record; v_pos bigint; v_all bigint; v_disc numeric; v_used uuid[] := '{}';
begin
  if not can_module('sales', 2) then raise exception 'not_allowed'; end if;
  if p_jobs is null or array_length(p_jobs, 1) is null then raise exception 'jobs_required'; end if;
  select count(distinct customer_id), count(distinct currency), min(customer_id::text)::uuid, min(currency)
    into v_customers, v_curs, v_customer, v_cur
  from jobs where id = any (p_jobs) and status <> 'cancelled' and invoice_id is null;
  if v_customers = 0 then raise exception 'jobs_required'; end if;
  if v_customers > 1 then raise exception 'jobs_mixed_customer'; end if;
  if v_curs > 1 then raise exception 'jobs_mixed_currency'; end if;
  select id into v_party from fin_parties where lab_customer_id = v_customer;
  if v_party is null then raise exception 'party_required'; end if;
  select inv_lab_vat into v_vat from companies where id = lab_company();
  for j in select * from jobs where id = any (p_jobs) and status <> 'cancelled' and invoice_id is null order by in_date, no loop
    select coalesce(sum(amount) filter (where amount > 0), 0), coalesce(sum(amount), 0) into v_pos, v_all from job_items where job_id = j.id;
    if v_pos <= 0 then continue; end if;
    v_used := v_used || j.id;
    v_disc := case when v_all < v_pos then round((1 - greatest(v_all, 0)::numeric / v_pos) * 100, 4) else 0 end;
    for li in select * from job_items where job_id = j.id and amount > 0 order by sort loop
      v_lines := v_lines || jsonb_build_object(
        'name', left(li.name || coalesce(' — ' || nullif(j.patient, ''), '') || ' (İş #' || j.no || ')', 300),
        'qty', li.qty, 'unit', 'adet', 'unit_price', round(li.amount::numeric / li.qty / 100, 4),
        'discount_pct', v_disc, 'vat_rate', coalesce(v_vat, 10), 'lab_product_id', li.product_id, 'job_id', j.id);
    end loop;
  end loop;
  if jsonb_array_length(v_lines) = 0 then raise exception 'jobs_empty'; end if;
  return inv_save(jsonb_build_object('direction', 'sale', 'party_id', v_party, 'currency', v_cur, 'invoice_date', current_date,
    'affects_balance', false, 'source', 'jobs', 'job_ids', to_jsonb(v_used), 'lines', v_lines));
end $$;
revoke execute on function inv_from_jobs(uuid[]) from public, anon;
grant execute on function inv_from_jobs(uuid[]) to authenticated;

-- Fatura kayıtları finanstan iptal edilmez (stok ve fatura durumu bozulmasın): faturadan iptal edilir
create or replace function fin_void(p_txn uuid, p_reason text) returns void
language plpgsql security definer set search_path = public as $$
declare t fin_txns;
begin
  select * into t from fin_txns where id = p_txn for update;
  if t.id is null then raise exception 'not_found'; end if;
  if not (can_module('finance', 3) or (t.kind = 'expense' and can_module('expenses', 3))) then raise exception 'not_allowed'; end if;
  if t.voided_at is not null then return; end if;
  if t.ref_type = 'invoice' then raise exception 'use_invoice_cancel'; end if;
  update fin_txns set voided_at = now(), voided_by = auth.uid(), void_reason = left(coalesce(p_reason, ''), 300) where id = p_txn;
  if t.lab_payment_id is not null then delete from lab_payments where id = t.lab_payment_id; end if;
end $$;
revoke execute on function fin_void(uuid, text) from public, anon;
grant execute on function fin_void(uuid, text) to authenticated;

