-- Alış / satış faturaları ve e-fatura (UBL-TR 1.2)
--  inv_invoices / inv_lines : fatura başlığı ve satırları (taslak → kesildi → iptal)
--  inv_save(jsonb)          : taslak kaydet (satırlar yeniden yazılır, tutarlar veritabanında hesaplanır)
--  inv_post(id)             : faturayı işle → cari + gelir/gider + KDV (finans), stok giriş/çıkış, SMM
--  inv_cancel(id, neden)    : işlenmiş faturayı iptal (finans iptal, stok hareketleri silinir)
--  inv_from_jobs(uuid[])    : teslim edilmiş laboratuvar işlerinden satış faturası taslağı
--  fin_party_ensure(jsonb)  : VKN / TCKN ile cari bul, yoksa aç (e-fatura içe aktarma)
-- Tekrar çalıştırılabilir. Önce 20261202000000_finance_core.sql ve 20261203000000_stock.sql.
